export function humanize(name) {
  if (FIELD_LABELS[name]) return FIELD_LABELS[name];
  const s = name.replace(/([a-z0-9])([A-Z])/g, "$1 $2").replace(/_/g, " ");
  return s.charAt(0).toUpperCase() + s.slice(1);
}

export function enumLabel(value) {
  if (ENUM_LABELS[value.name]) return ENUM_LABELS[value.name];
  // Regionen, Baudraten, Codecs usw. bleiben technisch (z. B. "EU_868", "BAUD_9600")
  if (/\d/.test(value.name) || /^[A-Z]{2,3}$/.test(value.name)) return value.name.replace(/^BAUD_/, "").replace(/_/g, " ");
  const n = value.name.replace(/_/g, " ").toLowerCase();
  return n.charAt(0).toUpperCase() + n.slice(1);
}

